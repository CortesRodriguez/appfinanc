-- Tabla 1: USUARIOS (Autenticación - RF-16, RF-17)
-- Almacena credenciales de usuarios registrados (contraseña o cuenta Google)
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255),          -- NULL si la cuenta se creó con Google
    google_id VARCHAR(255),              -- NULL si la cuenta usa contraseña
    created_at TIMESTAMPTZ
);

-- Índices únicos: búsquedas rápidas durante login y unicidad garantizada por el motor
CREATE UNIQUE INDEX ix_users_email ON users (email);
CREATE UNIQUE INDEX ix_users_username ON users (username);
CREATE UNIQUE INDEX ix_users_google_id ON users (google_id);

-- ============================================================================

-- Tabla 2: TOKENS REVOCADOS (Autenticación - RF-17.3: cerrar sesión)
-- Invalidar tokens JWT cuando el usuario cierra sesión
CREATE TABLE revoked_tokens (
    jti VARCHAR(64) PRIMARY KEY,
    revoked_at TIMESTAMPTZ
);

-- ============================================================================

-- Tabla 3: HISTORIAL DE CONSULTAS (Trazabilidad - RNF-01.2, RF-13, RF-19.1)
-- Registra cada consulta de indicador que hace el usuario
CREATE TABLE query_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36) NOT NULL,
    instrument VARCHAR(20) NOT NULL,
    indicator VARCHAR(20) NOT NULL,
    source VARCHAR(30) NOT NULL,
    processing_time_ms INTEGER NOT NULL,
    created_at TIMESTAMPTZ,

    user_id INTEGER REFERENCES users (id),
    is_regeneration BOOLEAN,
    explanation_text TEXT,
    variant INTEGER
);

-- Índice en user_id para buscar historial de un usuario
CREATE INDEX ix_query_logs_user_id ON query_logs (user_id);

-- ============================================================================

-- Tabla 4: VISITAS A INSTRUMENTOS (Perfil Adaptativo - RF-19.2, RF-19.3)
-- Registra cada vez que un usuario selecciona una acción
-- Separada de query_logs porque:
--   • Seleccionar 1 acción = 1 "acción del usuario"
--   • Pero dispara 4 consultas en paralelo (una por indicador)
--   • En query_logs quedan 4 filas, pero el usuario vio "una acción"
CREATE TABLE instrument_visits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (id),
    instrument VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ
);

-- Índice en user_id para calcular "¿qué acciones ve este usuario?"
CREATE INDEX ix_instrument_visits_user_id ON instrument_visits (user_id);

-- Nota sobre valores por defecto: created_at / revoked_at (UTC con zona horaria),
-- is_regeneration (FALSE) y variant (0) los asigna la aplicación (SQLAlchemy,
-- default= en los modelos), no el motor. Por eso no llevan DEFAULT en el DDL.

-- ============================================================================
-- RESUMEN DE TABLAS
-- ============================================================================

-- TABLA               FILAS      PROPÓSITO
-- ──────────────────────────────────────────────────────────────────────────
-- users               ~10        Credenciales (email, password_hash)
-- revoked_tokens      Variable   Lista de tokens invalidados
-- query_logs          ~1000s     Historial de cada indicador consultado
-- instrument_visits   ~100s      Resumen: qué acciones ve cada usuario
--
-- TOTAL: 4 tablas (+ alembic_version, tabla de control que crea Alembic
--   con la revisión del esquema aplicada)
-- NO HAY tabla de precios, NO HAY tabla de indicadores calculados
--   → Precios: se consultan en vivo (Yahoo Finance / Alpha Vantage)
--   → Indicadores: se calculan en memoria, se almacenan SOLO la explicación

-- ============================================================================
-- RELACIONES (Foreign Keys)
-- ============================================================================

-- query_logs.user_id → users.id (nullable: usuario anónimo puede consultar)
-- instrument_visits.user_id → users.id (NOT NULL: solo usuarios registrados)

-- ============================================================================
-- ÍNDICES OPTIMIZADOS
-- ============================================================================

-- ix_users_email (UNIQUE)
--   → Búsqueda rápida durante login: "¿Existe este email?"
--   → Query: SELECT id FROM users WHERE email = $1
--
-- ix_users_username (UNIQUE)
--   → Garantiza nombres de usuario únicos
--
-- ix_users_google_id (UNIQUE)
--   → Login con Google: "¿Existe una cuenta con este identificador?"
--   → Admite varios NULL (cuentas con contraseña), PostgreSQL no los considera duplicados

-- ix_query_logs_user_id
--   → Historial de consultas de un usuario
--   → Query: SELECT * FROM query_logs WHERE user_id = $1 ORDER BY created_at

-- ix_instrument_visits_user_id
--   → Calcular perfil adaptativo: "¿Cuántas veces vio esta acción?"
--   → Query: SELECT COUNT(*) FROM instrument_visits WHERE user_id = $1 AND instrument = $2

-- ============================================================================
-- CAMPOS Y TIPOS DE DATOS
-- ============================================================================

-- USERS
-- ─────
-- id (INTEGER GENERATED BY DEFAULT AS IDENTITY, PRIMARY KEY)
--   └─ Identificador único, generado por una columna identidad
-- username (VARCHAR 80, UNIQUE)
--   └─ Nombre de usuario único
-- email (VARCHAR 255, UNIQUE)
--   └─ Email único, usado para login
-- password_hash (VARCHAR 255, NULLABLE)
--   └─ Hash bcrypt de la contraseña (no la contraseña en plano)
--   └─ NULL en cuentas creadas con Google
-- google_id (VARCHAR 255, UNIQUE, NULLABLE)
--   └─ Identificador "sub" de Google (OAuth2/OIDC); NULL en cuentas con contraseña
-- created_at (TIMESTAMPTZ)
--   └─ Instante (con zona horaria, UTC) en que se registró el usuario

-- REVOKED_TOKENS
-- ───────────────
-- jti (VARCHAR 64, PRIMARY KEY)
--   └─ JWT ID (unique identifier del token revocado)
--   └─ Se extrae del payload del JWT al hacer logout
-- revoked_at (TIMESTAMPTZ)
--   └─ Timestamp cuando se revocó el token

-- QUERY_LOGS
-- ──────────
-- id (INTEGER IDENTITY, PRIMARY KEY)
--   └─ Identificador único de cada consulta
-- session_id (VARCHAR 36)
--   └─ Identificador de la sesión (UUID), para agrupar consultas del mismo usuario
-- instrument (VARCHAR 20)
--   └─ Símbolo de acción: FALABELLA.SN, SQM-B.SN, etc.
--   └─ PostgreSQL rechaza valores más largos: la app valida MAX_SYMBOL_LENGTH = 20 antes
-- indicator (VARCHAR 20)
--   └─ Nombre del indicador: rsi, medias_moviles, macd, bandas_bollinger
-- source (VARCHAR 30)
--   └─ De dónde vinieron los datos: yahoo_finance, alpha_vantage, cache
-- processing_time_ms (INTEGER)
--   └─ Cuánto tardó calcular el indicador (RNF-01.2: < 5 segundos)
-- created_at (TIMESTAMPTZ)
--   └─ Timestamp de la consulta
-- user_id (INTEGER, NULLABLE)
--   └─ Quién la hizo (NULL = usuario anónimo, NOT NULL = usuario registrado)
-- is_regeneration (BOOLEAN, la app asigna FALSE por defecto)
--   └─ ¿El usuario hizo clic en "No entendí, regenera"?
-- explanation_text (TEXT)
--   └─ Explicación generada (almacenada para trazabilidad)
-- variant (INTEGER, la app asigna 0 por defecto)
--   └─ Número de variante (0 = original, 1 = regenerada, 2 = re-regenerada, etc.)

-- INSTRUMENT_VISITS
-- ──────────────────
-- id (INTEGER IDENTITY, PRIMARY KEY)
--   └─ Identificador único de la visita
-- user_id (INTEGER, NOT NULL)
--   └─ Usuario registrado que seleccionó el instrumento
-- instrument (VARCHAR 20)
--   └─ Símbolo de acción: FALABELLA.SN, SQM-B.SN, etc.
-- created_at (TIMESTAMPTZ)
--   └─ Instante en que seleccionó

-- ============================================================================
-- CICLO DE VIDA DE DATOS
-- ============================================================================

-- INSERCIÓN (CREATE)
-- ──────────────────
-- 1. Usuario se registra
--    → INSERT INTO users (username, email, password_hash, created_at)
--
-- 2. Usuario inicia sesión
--    → SELECT id FROM users WHERE email = $1 (usa ix_users_email)
--    → JWT se genera (jti va al payload)
--
-- 3. Usuario consulta indicador
--    → INSERT INTO query_logs (session_id, instrument, indicator, source, ...)
--
-- 4. Usuario cierra sesión
--    → INSERT INTO revoked_tokens (jti)
--
-- 5. Usuario registrado selecciona acción
--    → INSERT INTO instrument_visits (user_id, instrument, created_at)

-- LECTURA (READ)
-- ──────────────
-- • Historial de usuario:
--   SELECT * FROM query_logs WHERE user_id = $1 ORDER BY created_at DESC
--
-- • Perfil adaptativo (¿cuántas veces vio esta acción?):
--   SELECT COUNT(*) FROM instrument_visits
--   WHERE user_id = $1 AND instrument = $2
--
-- • ¿Es token válido o revocado?:
--   SELECT 1 FROM revoked_tokens WHERE jti = $1

-- ACTUALIZACIÓN (UPDATE)
-- ──────────────────────
-- NO HAY updates. La BD es mostly append-only (inserts, no updates)

-- BORRADO (DELETE)
-- ────────────────
-- NO HAY deletes en producción. Los datos se conservan para auditoría

-- ============================================================================
-- VOLUMEN DE DATOS
-- ============================================================================

-- Escenario: 100 usuarios, cada uno hace 50 consultas
-- ───────────────────────────────────────────────────
-- users                  ~100 filas         (crecer con nuevos registros)
-- query_logs             ~5,000 filas       (50 consultas × 100 usuarios)
-- instrument_visits      ~5,000 filas       (promedio 50 visitas × 100 usuarios)
-- revoked_tokens         ~200 filas         (2 por usuario en promedio)
--
-- TOTAL: ~10,200 filas
-- Tamaño en disco: ~3-5 MB incluyendo índices (holgado incluso para el plan
--   gratuito de un PostgreSQL gestionado; explanation_text es la columna que más pesa)

-- ============================================================================
-- INTEGRIDAD REFERENCIAL
-- ============================================================================

-- FOREIGN KEY CONSTRAINTS:
-- ├─ query_logs.user_id → users.id
-- │  └─ ON DELETE: NO ACTION (no borrar usuarios con consultas)
-- │  └─ Tipo: NULLABLE (usuario anónimo = user_id IS NULL)
-- │
-- └─ instrument_visits.user_id → users.id
--    └─ ON DELETE: NO ACTION (no borrar usuarios con visitas)
--    └─ Tipo: NOT NULL (solo usuarios registrados)

